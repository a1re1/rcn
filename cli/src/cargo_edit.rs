/// Ensure `[dependencies]` contains each git dep (skip if the key already exists).
/// Returns the names that were newly inserted.
pub fn ensure_git_deps(
    cargo_toml: &str,
    deps: &[(String, GitDep)],
) -> Result<(String, Vec<String>)> {
    let mut doc = cargo_toml
        .parse::<DocumentMut>()
        .context("failed to parse Cargo.toml")?;
    let table = dependencies_table_mut(&mut doc)?;
    let mut added = Vec::new();
    for (name, dep) in deps {
        if table.contains_key(name) {
            continue;
        }
        let mut inline = toml_edit::InlineTable::new();
        inline.insert("git", Value::from(dep.git.as_str()));
        if !dep.rev.is_empty() {
            inline.insert("rev", Value::from(dep.rev.as_str()));
        }
        // Only emit package= when it differs from the dependency key.
        if !dep.package.is_empty() && dep.package != *name {
            inline.insert("package", Value::from(dep.package.as_str()));
        }
        if !dep.features.is_empty() {
            let mut arr = toml_edit::Array::new();
            for f in &dep.features {
                arr.push(f.as_str());
            }
            inline.insert("features", Value::Array(arr));
        }
        table.insert(name, Item::Value(Value::InlineTable(inline)));
        added.push(name.clone());
    }
    Ok((doc.to_string(), added))
}

/// Ensure `[dependencies]` contains each crates.io dep (skip if present).
/// Returns the names that were newly inserted.
pub fn ensure_crate_deps(
    cargo_toml: &str,
    deps: &[CrateDep],
) -> Result<(String, Vec<String>)> {
    let mut doc = cargo_toml
        .parse::<DocumentMut>()
        .context("failed to parse Cargo.toml")?;
    let table = dependencies_table_mut(&mut doc)?;
    let mut added = Vec::new();
    for dep in deps {
        if table.contains_key(&dep.name) {
            continue;
        }
        table.insert(&dep.name, Item::Value(Value::from(dep.version.as_str())));
        added.push(dep.name.clone());
    }
    Ok((doc.to_string(), added))
}

fn dependencies_table_mut(doc: &mut DocumentMut) -> Result<&mut Table> {
    if doc.get("dependencies").is_none() {
        doc["dependencies"] = Item::Table(Table::new());
    }
    doc["dependencies"]
        .as_table_mut()
        .ok_or_else(|| anyhow::anyhow!("[dependencies] is not a table"))
}

/// Read, transform, and write a consumer Cargo.toml in place.
pub fn update_cargo_toml(path: &Path, f: impl FnOnce(&str) -> Result<String>) -> Result<()> {
    let original = std::fs::read_to_string(path)
        .with_context(|| format!("failed to read {}", path.display()))?;
    let next = f(&original)?;
    if next != original {
        std::fs::write(path, next)
            .with_context(|| format!("failed to write {}", path.display()))?;
    }
    Ok(())
}

/// Apply git deps from a registry map onto a Cargo.toml string.
pub fn inject_gpui_deps(
    cargo_toml: &str,
    gpui_deps: &std::collections::BTreeMap<String, GitDep>,
) -> Result<(String, Vec<String>)> {
    let pairs: Vec<(String, GitDep)> = gpui_deps
        .iter()
        .map(|(k, v)| (k.clone(), v.clone()))
        .collect();
    ensure_git_deps(cargo_toml, &pairs)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::registry::GitDep;
    use std::collections::BTreeMap;

    #[test]
    fn detects_hello_world_variants() {
        assert!(is_hello_world_main(r#"fn main() { println!("Hello, world!"); }"#));
        assert!(is_hello_world_main(
            r#"
            // comment
            fn main() {
                println!("Hello, world!");
            }
            "#
        ));
        assert!(!is_hello_world_main(
            r#"fn main() { println!("something else"); }"#
        ));
        assert!(!is_hello_world_main(
            r#"fn main() { println!("Hello, world!"); do_more(); }"#
        ));
    }

    #[test]
    fn injects_git_deps_preserving_existing() {
        let original = r#"[package]
name = "demo"
version = "0.1.0"
edition = "2024"

[dependencies]
serde = "1"
"#;
        let mut gpui = BTreeMap::new();
        gpui.insert(
            "gpui".into(),
            GitDep {
                git: "https://github.com/zed-industries/zed".into(),
                rev: "abc".into(),
                package: "gpui".into(),
                features: vec![],
            },
        );
        gpui.insert(
            "gpui_platform".into(),
            GitDep {
                git: "https://github.com/zed-industries/zed".into(),
                rev: "abc".into(),
                package: "gpui_platform".into(),
                features: vec!["font-kit".into()],
            },
        );
        let (next, added) = inject_gpui_deps(original, &gpui).unwrap();
        assert_eq!(added, vec!["gpui".to_string(), "gpui_platform".to_string()]);
        assert!(next.contains("serde = \"1\""));
        assert!(next.contains("gpui"));
        assert!(next.contains("rev = \"abc\""));
        assert!(next.contains("font-kit"));
        // second pass is idempotent
        let (again, added2) = inject_gpui_deps(&next, &gpui).unwrap();
        assert!(added2.is_empty());
        assert_eq!(again, next);
    }

    #[test]
    fn skips_existing_crate_deps() {
        let original = r#"[package]
name = "demo"
version = "0.1.0"

[dependencies]
unicode-segmentation = "1"
"#;
        let deps = vec![
            CrateDep {
                name: "unicode-segmentation".into(),
                version: "1".into(),
            },
            CrateDep {
                name: "anyhow".into(),
                version: "1".into(),
            },
        ];
        let (next, added) = ensure_crate_deps(original, &deps).unwrap();
        assert_eq!(added, vec!["anyhow".to_string()]);
        assert!(next.contains("unicode-segmentation = \"1\""));
        assert!(next.contains("anyhow = \"1\""));
    }

    #[test]
    fn errors_on_bad_toml() {
        let err = ensure_crate_deps("[[[not toml", &[]).unwrap_err().to_string();
        assert!(err.contains("parse"), "{err}");
    }
}

//! Cargo.toml dependency injection and hello-world `main.rs` detection.

use anyhow::{Context, Result};
use std::path::Path;
use toml_edit::{DocumentMut, Item, Table, Value};

use crate::registry::{CrateDep, GitDep};

/// True when `main.rs` is still the untouched `cargo new` hello-world
/// (`fn main() { println!("Hello, world!"); }` modulo whitespace/comments).
pub fn is_hello_world_main(source: &str) -> bool {
    let stripped = strip_rs_trivia(source);
    matches!(
        stripped.as_str(),
        "fnmain(){println!(\"Hello, world!\");}"
            | "fnmain(){println!(\"Hello, world!\")}"
            | "pubfnmain(){println!(\"Hello, world!\");}"
            | "pubfnmain(){println!(\"Hello, world!\")}"
    )
}

/// Strip line/block comments and all whitespace for hello-world comparison.
fn strip_rs_trivia(source: &str) -> String {
    let mut out = String::with_capacity(source.len());
    let bytes = source.as_bytes();
    let mut i = 0;
    while i < bytes.len() {
        // line comment
        if bytes[i] == b'/' && i + 1 < bytes.len() && bytes[i + 1] == b'/' {
            i += 2;
            while i < bytes.len() && bytes[i] != b'\n' {
                i += 1;
            }
            continue;
        }
        // block comment
        if bytes[i] == b'/' && i + 1 < bytes.len() && bytes[i + 1] == b'*' {
            i += 2;
            while i + 1 < bytes.len() && !(bytes[i] == b'*' && bytes[i + 1] == b'/') {
                i += 1;
            }
            i = (i + 2).min(bytes.len());
            continue;
        }
        // string literal — keep contents so we can match the println payload
        if bytes[i] == b'"' {
            out.push('"');
            i += 1;
            while i < bytes.len() {
                let c = bytes[i] as char;
                out.push(c);
                i += 1;
                if c == '\\' && i < bytes.len() {
                    out.push(bytes[i] as char);
                    i += 1;
                    continue;
                }
                if c == '"' {
                    break;
                }
            }
            continue;
        }
        let c = bytes[i] as char;
        if !c.is_whitespace() {
            out.push(c);
        }
        i += 1;
    }
    out
}

/// Minimal runnable gpui app scaffold written when `main.rs` is still hello-world.
pub fn scaffold_main_rs() -> &'static str {
    r#"//! Generated by `rcn init` — a minimal gpui app using the vendored Theme.

// Vendored rcn modules; dead_code allowed until your app uses them all.
#[allow(dead_code)]
mod assets;
#[allow(dead_code)]
mod components;
#[allow(dead_code)]
mod motion;
#[allow(dead_code)]
mod theme;

use gpui::{
    div, px, size, App, AppContext, Application, Bounds, Context, IntoElement,
    ParentElement, Render, Styled, Window, WindowBounds, WindowOptions,
};
use theme::Theme;

fn main() {
    // At this gpui rev the platform lives in the gpui_platform crate.
    let platform = gpui_platform::current_platform(false);
    let app = Application::with_platform(platform);
    app.run(|cx: &mut App| {
        cx.set_global(Theme::light());
        let bounds = Bounds::centered(None, size(px(480.0), px(320.0)), cx);
        cx.open_window(
            WindowOptions {
                window_bounds: Some(WindowBounds::Windowed(bounds)),
                titlebar: Some(gpui::TitlebarOptions {
                    title: Some("rcn".into()),
                    ..Default::default()
                }),
                ..Default::default()
            },
            |_window, cx| cx.new(|_| Ready),
        )
        .expect("failed to open window");
        cx.activate(true);
    });
}

struct Ready;

impl Render for Ready {
    fn render(&mut self, _window: &mut Window, cx: &mut Context<Self>) -> impl IntoElement {
        let theme = Theme::of(cx);
        div()
            .flex()
            .items_center()
            .justify_center()
            .size_full()
            .bg(theme.background)
            .text_color(theme.foreground)
            .child("rcn is ready")
    }
}
"#
}


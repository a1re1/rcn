static LEDGER_MAP: OnceLock<HashMap<&'static str, &'static coverage::Entry>> = OnceLock::new();

fn ledger_map() -> &'static HashMap<&'static str, &'static coverage::Entry> {
    LEDGER_MAP.get_or_init(|| coverage::LEDGER.iter().map(|e| (e.name, e)).collect())
}


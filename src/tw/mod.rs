//! tw — Tailwind class-string → gpui [`StyleRefinement`] parser.
//!
//! `parse(theme, "flex h-9 px-2.5 bg-primary hover:bg-primary/80")` resolves a
//! Tailwind class string into per-state [`StyleRefinement`] buckets (base,
//! hover, focus, focus-visible, active, disabled) that plug directly into
//! gpui's state-style hooks (`hover()`, `focus_visible()`, `active()` all take
//! `FnOnce(StyleRefinement) -> StyleRefinement`). Because every rcn component
//! implements [`Styled`] (the className-passthrough convention), the extension
//! traits at the bottom deliver a whole class string to any component in one
//! call.
//!
//! ## Registry layout
//!
//! Utilities are implemented in per-family modules mirroring the Tailwind docs
//! chapters (`layout`, `flex_grid`, `spacing`, `sizing`, `typography`,
//! `backgrounds`, `borders`, `effects`, `transforms`, `interactivity`), each
//! registered in [`HANDLERS`] and carrying its own unit tests. What a family
//! does not claim falls through to the coverage ledger ([`coverage`]): every
//! utility root from the canonical Tailwind manifest (`manifest.json`,
//! generated by `scripts/pull-tailwind.py`) is classified there as
//! `Supported`, `Todo`, or `NoEquivalent(reason)`. `NoEquivalent` tokens are
//! reported in [`TwStyles::skipped`]; everything else unhandled lands in
//! [`TwStyles::unknown`]. Enforcement tests in `coverage` keep the ledger and
//! the handlers in lockstep.
//!
//! ## Deliberate deviations from real Tailwind/CSS
//!
//! - **Order-sensitive**: later classes in the string win over earlier ones
//!   for the same property (like `tailwind-merge`, unlike raw CSS selector
//!   specificity). `dark:` and state variants therefore belong *after* the
//!   classes they override, which is how shadcn's cva strings are written.
//! - **`dark:` resolves at parse time** against `theme.dark` — the token is
//!   applied or dropped, not kept as a runtime condition.
//! - **`ring-*` synthesizes a box shadow** (zero blur, spread = ring width),
//!   appended to the bucket's `box_shadow`, matching `motion::focus_ring`.
//! - **`translate-x/y-*` map to `left`/`top` insets** — gpui has no
//!   transforms. The element needs `relative` for the offset to take effect.
//! - **Logical properties assume LTR**: `ps`/`ms`/`start`/`border-s`/
//!   `rounded-ss` map to their left/physical equivalents.
//! - **No transitions/animations**: state changes are instant in gpui; motion
//!   timings live in `crate::motion`.


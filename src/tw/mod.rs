/// Tailwind length: `2.5` → 10px (4px scale), `px` → 1px, `[Npx]`/`[Nrem]`
/// arbitrary values.
pub(super) fn scale_px(v: &str) -> Option<Pixels> {
    if v == "px" {
        return Some(px(1.));
    }
    if let Some(inner) = v.strip_prefix('[').and_then(|x| x.strip_suffix(']')) {
        if let Some(n) = inner.strip_suffix("px") {
            return n.parse::<f32>().ok().map(px);
        }
        if let Some(n) = inner.strip_suffix("rem") {
            return n.parse::<f32>().ok().map(|r| px(r * 16.));
        }
        return None;
    }
    v.parse::<f32>().ok().map(|n| px(n * 4.))
}

/// Length values for sizing/inset roots: everything [`scale_px`] accepts,
/// plus `full`, fractions (`1/2` → 50%), and `auto`.
pub(super) fn scale_len(v: &str) -> Option<Length> {
    match v {
        "auto" => return Some(Length::Auto),
        "full" => return Some(relative(1.).into()),
        _ => {}
    }
    if let Some((num, den)) = v.split_once('/')
        && let (Ok(n), Ok(d)) = (num.parse::<f32>(), den.parse::<f32>())
        && d != 0.
    {
        return Some(relative(n / d).into());
    }
    scale_px(v).map(Into::into)
}

/// Resolve `primary`, `red-500`, `muted-foreground/50`, `[#323232]`, … —
/// theme tokens first, then the generated default palette, then arbitrary
/// hex. `/NN` suffixes apply alpha.
pub(super) fn color(theme: &Theme, spec: &str) -> Option<Hsla> {
    let (name, alpha_pct) = match spec.rsplit_once('/') {
        Some((n, a)) => (n, Some(a)),
        None => (spec, None),
    };
    let base: Hsla = if let Some(inner) = name.strip_prefix('[').and_then(|x| x.strip_suffix(']')) {
        let hex = inner.strip_prefix('#')?;
        if hex.len() != 6 {
            return None;
        }
        gpui::rgb(u32::from_str_radix(hex, 16).ok()?).into()
    } else if let Some(token) = theme_token(theme, name) {
        token
    } else {
        match name {
            "transparent" => gpui::transparent_black(),
            _ => palette::palette(name)?,
        }
    };
    match alpha_pct {
        Some(a) => Some(alpha(base, a.parse::<f32>().ok()? / 100.)),
        None => Some(base),
    }
}

/// rcn's semantic theme tokens (shadcn CSS-variable names).
fn theme_token(theme: &Theme, name: &str) -> Option<Hsla> {
    Some(match name {
        "background" => theme.background,
        "foreground" => theme.foreground,
        "card" => theme.card,
        "card-foreground" => theme.card_foreground,
        "popover" => theme.popover,
        "popover-foreground" => theme.popover_foreground,
        "primary" => theme.primary,
        "primary-foreground" => theme.primary_foreground,
        "secondary" => theme.secondary,
        "secondary-foreground" => theme.secondary_foreground,
        "muted" => theme.muted,
        "muted-foreground" => theme.muted_foreground,
        "accent" => theme.accent,
        "accent-foreground" => theme.accent_foreground,
        "destructive" => theme.destructive,
        "destructive-foreground" => theme.destructive_foreground,
        "border" => theme.border,
        "input" => theme.input,
        "ring" => theme.ring,
        _ => return None,
    })
}

/// Radius values: the theme-mapped scale, fixed upper scale, `full`/`none`,
/// `[Npx]`, and shadcn's `[min(var(--radius-SCALE),Npx)]` clamp.
pub(super) fn radius(theme: &Theme, v: &str) -> Option<Pixels> {
    Some(match v {
        "none" => px(0.),
        "xs" => px(2.),
        "sm" => theme.radius_sm(),
        "md" => theme.radius_md(),
        "lg" => theme.radius_lg(),
        "xl" => theme.radius_xl(),
        "2xl" => px(16.),
        "3xl" => px(24.),
        "4xl" => px(32.),
        "full" => px(9999.),
        _ => return arbitrary_radius(theme, v),
    })
}

fn arbitrary_radius(theme: &Theme, v: &str) -> Option<Pixels> {
    let inner = v.strip_prefix('[')?.strip_suffix(']')?;
    if let Some(n) = inner.strip_suffix("px") {
        return n.parse::<f32>().ok().map(px);
    }
    let rest = inner.strip_prefix("min(var(--radius-")?;
    let (scale, tail) = rest.split_once(')')?;
    let cap: f32 = tail.strip_prefix(',')?.strip_suffix("px)")?.parse().ok()?;
    let base = match scale {
        "sm" => theme.radius_sm(),
        "md" => theme.radius_md(),
        "lg" => theme.radius_lg(),
        "xl" => theme.radius_xl(),
        _ => return None,
    };
    Some(base.min(px(cap)))
}

